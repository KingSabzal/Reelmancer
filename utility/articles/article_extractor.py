CATEGORY_STYLE_HINTS = {
    "Technology": ["AI & Tech", "Tech Review", "Cyberpunk", "Robot", "Singularity"],
    "Science": ["Physics", "Astronomy", "Space", "Biology", "Deep Dive", "Quantum"],
    "Business": ["Business", "Finance", "Crypto", "Data Story", "Analysis"],
    "Health": ["Psychology", "Fitness", "Explainer", "How-To"],
    "Politics": ["News Report", "Analysis", "Breakdown"],
    "Sports": ["Sports", "Countdown", "Motivational"],
    "Entertainment": ["Comedy", "Cinematic", "Review", "Mockumentary"],
    "Culture": ["Documentary", "Historical", "Travel Vlog", "Urban"],
    "Mystery": ["Mystery", "True Crime", "UFO", "Lost Civilization"],
    "Environment": ["Nature", "Ocean", "Wildlife", "Forest", "Arctic"],
}

CATEGORY_KEYWORDS = {
    "Technology": ["ai", "software", "chip", "app", "startup", "algorithm", "robot", "data",
                    "computer", "quantum", "cyber", "internet", "phone", "model"],
    "Science": ["study", "research", "scientist", "nasa", "space", "physics", "gene", "brain",
                 "discovery", "experiment", "telescope", "cells", "species"],
    "Business": ["market", "economy", "revenue", "company", "stock", "investor", "price",
                  "billion", "million", "profit", "trade", "bank"],
    "Health": ["health", "patient", "disease", "doctor", "vaccine", "mental", "sleep", "diet",
                "therapy", "cancer", "medical"],
    "Politics": ["government", "election", "president", "minister", "policy", "law", "senate",
                  "parliament", "vote", "court"],
    "Sports": ["match", "player", "team", "league", "goal", "championship", "olympic", "coach"],
    "Entertainment": ["film", "movie", "album", "series", "actor", "music", "show", "netflix"],
    "Mystery": ["mystery", "unexplained", "unknown", "secret", "ancient", "disappeared"],
    "Environment": ["climate", "ocean", "forest", "wildlife", "emissions", "species", "pollution",
                     "temperature", "ice", "coral"],
}


def categorize(article: Article) -> str:
    """Guess the subject area, weighting the title far above the body text."""
    title = f" {article.title.lower()} "
    body = f" {article.text[:2000].lower()} "
    scores: Dict[str, float] = {}
    for category, words in CATEGORY_KEYWORDS.items():
        score = 0.0
        for word in words:
            # Whole-word matches only, so "ai" does not match "said" or "again".
            pattern = r"\b" + re.escape(word) + r"\b"
            score += len(re.findall(pattern, title)) * 5.0
            score += len(re.findall(pattern, body)) * 1.0
        scores[category] = score
    best = max(scores.items(), key=lambda item: item[1])
    # A weak signal means the text is general interest rather than a specialist topic.
    return best[0] if best[1] >= 3 else "Culture"


def suggest_settings(
    article: Article, duration_seconds: Optional[int] = None, analysis: Any = None
) -> Dict[str, Any]:
    """Derive the full set of video settings from an extracted and analyzed article."""
    from utility.publishing.algorithmic_standards import aspect_ratio_for_duration
    from utility.video.caption_styles import caption_style_for_video_style
    from utility.audio.intelligent_voice_selector import IntelligentVoiceSelector
    from utility.media.media_sources import music_moods_for_style
    from utility.content.video_styles import VIDEO_STYLES, get_style

    if analysis is None:
        from utility.articles.article_analyzer import analyze as _analyze

        analysis = _analyze(article)
    if duration_seconds is None:
        duration_seconds = analysis.recommended_duration

    category = categorize(article)
    candidates = [s for s in CATEGORY_STYLE_HINTS.get(category, []) if s in VIDEO_STYLES]
    style_name = _style_for_emotion(analysis.emotion, candidates)
    style = get_style(style_name)
    voice = IntelligentVoiceSelector().select(style_name, analysis.clean_title)

    return {
        "topic": analysis.clean_title,
        "summary": analysis.summary,
        "emotion": analysis.emotion,
        "substance_score": round(analysis.substance_score, 1),
        "recommended_duration": analysis.recommended_duration,
        "duration_range": analysis.duration_range,
        "key_facts": [f.text for f in analysis.key_facts[:6]],
        "numbers": analysis.numbers[:8],
        "entities": analysis.entities[:8],
        "quotes": analysis.quotes[:3],
        "category": category,
        "video_style": style_name,
        "style_options": candidates or ["Documentary"],
        "voice_id": voice["voice_id"],
        "voice_name": voice["name"],
        "duration_seconds": duration_seconds,
        "aspect_ratio": aspect_ratio_for_duration(duration_seconds),
        "caption_style": caption_style_for_video_style(style_name, duration_seconds),
        "music_mood": music_moods_for_style(style_name),
        "sfx_density": style["sfx_density"],
        "source_url": article.url,
        "source_site": article.site,
    }


def _style_for_emotion(emotion: str, candidates: List[str]) -> str:
    """Pick the style that matches the article's emotional angle."""
    from utility.content.video_styles import VIDEO_STYLES

    preference = {
        "alarming": ["Dystopian", "News Report", "Deep Dive", "Documentary"],
        "hopeful": ["Motivational", "Explainer", "Bright Cheerful", "Documentary"],
        "surprising": ["Mystery", "What If", "Deep Dive", "Explainer"],
        "controversial": ["Analysis", "News Report", "Breakdown", "True Crime"],
        "inspiring": ["Motivational", "Cinematic", "Documentary", "Epic Trailer"],
    }
    for name in preference.get(emotion, []):
        if name in candidates and name in VIDEO_STYLES:
            return name
    if candidates:
        return candidates[0]
    for name in preference.get(emotion, []):
        if name in VIDEO_STYLES:
            return name
    return "Documentary"


def build_script_brief(article: Article) -> str:
    """Build the source material block handed to the script generator."""
    parts = [f"SOURCE ARTICLE: {article.title}"]
    if article.site:
        parts.append(f"PUBLISHER: {article.site}")
    if article.published:
        parts.append(f"PUBLISHED: {article.published}")
    parts.append(f"URL: {article.url}")
    parts.append("")
    parts.append("ARTICLE CONTENT:")
    parts.append(article.text)
    return "\n".join(parts)
